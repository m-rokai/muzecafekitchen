create table public.orders (
  id bigint generated by default as identity primary key,
  public_id uuid not null default gen_random_uuid() unique,
  customer_id uuid not null references auth.users(id) on delete restrict,
  idempotency_key text not null check (char_length(idempotency_key) between 16 and 128),
  request_hash text not null check (request_hash ~ '^[0-9a-f]{64}$'),
  pickup_number integer not null check (pickup_number > 0),
  customer_name text not null,
  email text,
  status public.order_status not null default 'pending',
  subtotal_cents integer not null default 0 check (subtotal_cents >= 0),
  tax_cents integer not null default 0 check (tax_cents >= 0),
  total_cents integer not null default 0 check (total_cents >= 0),
  subtotal numeric(10, 2) generated always as ((subtotal_cents::numeric) / 100) stored,
  tax numeric(10, 2) generated always as ((tax_cents::numeric) / 100) stored,
  total numeric(10, 2) generated always as ((total_cents::numeric) / 100) stored,
  notes text,
  cancellation_reason text,
  cancelled_by text check (cancelled_by in ('customer', 'staff') or cancelled_by is null),
  pickup_reminder_sent boolean not null default false,
  payment_status public.payment_status not null default 'unpaid',
  payment_method public.payment_method not null default 'cash',
  payment_provider public.payment_provider,
  payment_reference text,
  payment_updated_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (customer_id, idempotency_key)
);

