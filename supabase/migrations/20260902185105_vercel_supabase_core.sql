create or replace function private.enforce_order_status_transition()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if new.status = old.status then
    return new;
  end if;

  if new.status = 'cancelled' and old.status in ('pending', 'preparing', 'ready') then
    return new;
  end if;

  if (old.status = 'pending' and new.status = 'preparing')
    or (old.status = 'preparing' and new.status = 'ready')
    or (old.status = 'ready' and new.status = 'completed') then
    return new;
  end if;

  raise exception 'Illegal order status transition from % to %', old.status, new.status
    using errcode = 'check_violation';
end;
$$;

create trigger orders_enforce_status_transition
before update of status on public.orders
for each row execute function private.enforce_order_status_transition();

revoke all on function private.enforce_order_status_transition() from public;

create or replace function private.broadcast_kitchen_change()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if tg_table_name = 'settings'
    and coalesce(new.key, old.key) not in ('kitchen_open', 'kitchen_closed_message') then
    return null;
  end if;

  perform realtime.broadcast_changes(
    'kitchen',
    tg_op,
    tg_op,
    tg_table_name,
    tg_table_schema,
    new,
    old
  );
  return null;
end;
$$;

revoke all on function private.broadcast_kitchen_change() from public;

create trigger orders_broadcast_kitchen_change
after insert or update or delete on public.orders
for each row execute function private.broadcast_kitchen_change();

create trigger settings_broadcast_kitchen_change
after insert or update or delete on public.settings
for each row execute function private.broadcast_kitchen_change();

